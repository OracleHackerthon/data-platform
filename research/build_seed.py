SEED = 20261016
N_CORR, N_MISSING = 32, 8
N_SYNTH = 1000
DATASET_ID, TASK_ID = 1, 1
# 업체 ID: A=1, B=2, C=3, D=4 (API_CONTRACT 공통 규칙). 목표 TP/FP 개수 (불량 104, 정상 1,463 기준)
VENDOR_TARGETS = {1: (57, 117), 2: (81, 73), 3: (44, 44)}

src, out = Path(sys.argv[1]), Path(sys.argv[2])
out.mkdir(parents=True, exist_ok=True)
rng = random.Random(SEED)

# ---------- 읽기 ----------
rows = [[None if v == "NaN" else float(v) for v in line.split()]
        for line in (src / "secom.data").read_text().splitlines()]
lab_lines = [line.split(" ", 1) for line in (src / "secom_labels.data").read_text().splitlines()]
labels = [1 if l == "1" else 0 for l, _ in lab_lines]  # 원본 -1(정상)/1(불량) → 0/1
stamps = [datetime.strptime(t.strip().strip('"'), "%d/%m/%Y %H:%M:%S") for _, t in lab_lines]
n, m = len(rows), len(rows[0])


def col(j):
    return [r[j] for r in rows]


def miss_rate(j):
    return sum(v is None for v in col(j)) / n


def corr_with_label(j):
    pairs = [(v, y) for v, y in zip(col(j), labels) if v is not None]
    if len(pairs) < 30:
        return 0.0
    xs, ys = [p[0] for p in pairs], [p[1] for p in pairs]
    mx, my = sum(xs) / len(xs), sum(ys) / len(ys)
    sxy = sum((x - mx) * (y - my) for x, y in pairs)
    sxx = sum((x - mx) ** 2 for x in xs)
    syy = sum((y - my) ** 2 for y in ys)
    return 0.0 if sxx == 0 or syy == 0 else abs(sxy / math.sqrt(sxx * syy))


# ---------- 컬럼 고르기 ----------
nonconst = [j for j in range(m) if len({v for v in col(j) if v is not None}) > 1]
scored = [(corr_with_label(j), miss_rate(j), j) for j in nonconst]
low_miss = sorted([s for s in scored if s[1] < 0.3], reverse=True)[:N_CORR]
high_miss = sorted([s for s in scored if s[1] >= 0.3], reverse=True)[:N_MISSING]
chosen = sorted(low_miss + high_miss, key=lambda s: s[2])
cols = [s[2] for s in chosen]
names = [f"s_{j + 1:03d}" for j in cols]

with open(out / "columns.txt", "w", encoding="utf-8") as f:
    f.write(f"원본 {m}개 중 상수 컬럼 {m - len(nonconst)}개 제외. 결측 30% 미만에서 불량 상관 상위 {N_CORR}개 + "
            f"결측 30% 이상에서 불량 상관 상위 {N_MISSING}개 (개선 제안용).\n")
    for (c, mr, j), name in zip(chosen, names):
        f.write(f"{name}\tmissing={mr:.3f}\t|corr|={c:.3f}\n")


def fmt(v):
    if v is None:
        return "NULL"
    s = f"{v:.6g}"
    return s


def ts_sql(t):
    return f"TIMESTAMP '{t:%Y-%m-%d %H:%M:%S}'"


def insert_all(table, columns, value_rows, batch=100):
    """INSERT ALL 묶음 (Database Actions 의 Run Script 로 실행)."""
    parts = []
    head = f"  INTO {table} ({', '.join(columns)}) VALUES "
    for i in range(0, len(value_rows), batch):
        chunk = value_rows[i:i + batch]
        body = "\n".join(head + "(" + ", ".join(v) + ")" for v in chunk)
        parts.append(f"INSERT ALL\n{body}\nSELECT 1 FROM dual;\n")
    parts.append("COMMIT;\n")
    return "\n".join(parts)


