# ---------- 04 합성 (클래스별 평균·공분산 샘플링) ----------
k = len(cols)


def class_stats(cls):
    idx = [i for i in range(n) if labels[i] == cls]
    means = []
    for j in cols:
        vals = [rows[i][j] for i in idx if rows[i][j] is not None]
        means.append(sum(vals) / len(vals) if vals else 0.0)
    filled = [[rows[i][j] if rows[i][j] is not None else means[a] for a, j in enumerate(cols)] for i in idx]
    cov = [[0.0] * k for _ in range(k)]
    for x in filled:
        d = [x[a] - means[a] for a in range(k)]
        for a in range(k):
            for b in range(a, k):
                cov[a][b] += d[a] * d[b]
    for a in range(k):
        for b in range(a, k):
            cov[a][b] /= max(len(filled) - 1, 1)
            cov[b][a] = cov[a][b]
    return means, cov


def cholesky(a):
    """양의 정부호가 아니면 대각에 작은 값을 더해 다시 시도."""
    jitter = 1e-9
    while True:
        L = [[0.0] * k for _ in range(k)]
        ok = True
        for i in range(k):
            for j in range(i + 1):
                s = a[i][j] - sum(L[i][p] * L[j][p] for p in range(j))
                if i == j:
                    s += jitter * (a[i][i] + 1e-12)
                    if s <= 0:
                        ok = False
                        break
                    L[i][j] = math.sqrt(s)
                else:
                    L[i][j] = s / L[j][j]
            if not ok:
                break
        if ok:
            return L
        jitter *= 10


def col_bounds(j):
    vals = [v for v in col(j) if v is not None]
    return min(vals), max(vals)


bounds = [col_bounds(j) for j in cols]
n_fail_synth = round(N_SYNTH * sum(labels) / n)
synth = []
for cls, count in [(0, N_SYNTH - n_fail_synth), (1, n_fail_synth)]:
    means, cov = class_stats(cls)
    L = cholesky(cov)
    for _ in range(count):
        z = [rng.gauss(0, 1) for _ in range(k)]
        x = [means[a] + sum(L[a][p] * z[p] for p in range(a + 1)) for a in range(k)]
        x = [min(max(v, lo), hi) for v, (lo, hi) in zip(x, bounds)]  # 원본 범위 안으로
        synth.append((x, cls))
rng.shuffle(synth)
syn_cols = ["dataset_id", "row_id"] + names + ["label"]
syn_vals = [[str(DATASET_ID), str(i + 1)] + [fmt(v) for v in x] + [str(y)] for i, (x, y) in enumerate(synth)]
(out / "04_synth_rows.sql").write_text(
    f"-- 합성 {N_SYNTH}행 (중간 수준: 클래스별 평균·공분산 샘플링, 결측은 평균으로 채운 뒤 생성). 02 다음에 실행.\n"
    + insert_all("synth_rows", syn_cols, syn_vals), encoding="utf-8")
with open(out / "synth_rows.csv", "w", newline="", encoding="utf-8") as f:
    w = csv.writer(f)
    w.writerow([c.upper() for c in syn_cols])
    w.writerows([[DATASET_ID, i + 1] + [fmt(v) for v in x] + [y] for i, (x, y) in enumerate(synth)])

# ---------- 05 예측값 (사전 생성, 목표 TP/FP 개수로 정확히 맞춤) ----------
pos = [i for i in range(n) if labels[i] == 1]
neg = [i for i in range(n) if labels[i] == 0]
pred_vals, pred_csv, expect = [], [], {}
for vid, (tp, fp) in VENDOR_TARGETS.items():
    hit = set(rng.sample(pos, tp)) | set(rng.sample(neg, fp))
    for i in range(n):
        p = 1 if i in hit else 0
        pred_vals.append([str(vid), str(TASK_ID), str(i + 1), str(p)])
        pred_csv.append([vid, TASK_ID, i + 1, p])
    tn = len(neg) - fp
    expect[vid] = ((tp + tn) / n, tp / len(pos), fp / len(neg))
(out / "05_predictions.sql").write_text(
    "-- 업체 A/B/C 예측값 (사전 생성). 02 다음에 실행.\n"
    + insert_all("predictions", ["vendor_id", "task_id", "row_id", "predicted"], pred_vals, batch=500), encoding="utf-8")
with open(out / "predictions.csv", "w", newline="", encoding="utf-8") as f:
    w = csv.writer(f)
    w.writerow(["VENDOR_ID", "TASK_ID", "ROW_ID", "PREDICTED"])
    w.writerows(pred_csv)

# ---------- 06 시드 제출 (업체 A·C, 앱과 같은 채점 SQL) ----------
score_sql = """INSERT INTO submissions (task_id, vendor_id, accuracy, recall, fpr)
SELECT p.task_id, p.vendor_id,
  AVG(CASE WHEN p.predicted = r.label THEN 1 ELSE 0 END),
  SUM(CASE WHEN p.predicted = 1 AND r.label = 1 THEN 1 ELSE 0 END) / NULLIF(SUM(CASE WHEN r.label = 1 THEN 1 ELSE 0 END), 0),
  SUM(CASE WHEN p.predicted = 1 AND r.label = 0 THEN 1 ELSE 0 END) / NULLIF(SUM(CASE WHEN r.label = 0 THEN 1 ELSE 0 END), 0)
FROM predictions p
JOIN tasks t    ON t.id = p.task_id
JOIN raw_rows r ON r.dataset_id = t.dataset_id AND r.row_id = p.row_id
WHERE p.task_id = {task} AND p.vendor_id = {vid}
GROUP BY p.task_id, p.vendor_id;
"""
subs = "-- 업체 A·C 시드 제출. 03, 05 다음에 실행. 업체 B 는 시연에서 직접 제출한다.\n"
subs += "\n".join(score_sql.format(task=TASK_ID, vid=v) for v in (1, 3)) + "COMMIT;\n"
subs += "\n-- 확인: 기대값\n" + "".join(
    f"--   vendor {v}: accuracy={a:.4f} recall={r:.4f} fpr={f:.4f}\n" for v, (a, r, f) in expect.items())
